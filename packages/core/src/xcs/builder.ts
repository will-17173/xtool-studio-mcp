/**
 * Serialize the neutral Design model to the xTool `.xcs` file format.
 *
 * The `.xcs` format is community-reverse-engineered (see docs/xcs-format.md).
 * Key facts this implementation relies on (high confidence, confirmed against
 * real Studio-produced sample files and two independent generators):
 *
 *  - `.xcs` is plain, uncompressed JSON.
 *  - Shapes ("displays") live in `canvas[0].displays`; coordinates are mm,
 *    origin = top-left of each shape's bounding box.
 *  - Laser parameters do NOT live on the shape. They live in a parallel
 *    `device.data` structure: a JS Map serialized as
 *    `{ "dataType": "Map", "value": [[canvasId, {...}]] }`, whose per-canvas
 *    object contains a nested `displays` Map keyed by shape id.
 *  - Passes are written as `repeat` (not "passes").
 *  - A CIRCLE must set `scale = width / 5900` or Studio renders it invisible.
 *
 * This targets the single-file `.xcs` JSON (the well-trodden D1/F1-class path),
 * not the newer zip-based `.xs` workspace bundle.
 */
import { getMachine } from "../knowledge.js";
import type { LaserCategory, Machine } from "../types.js";
import { shapeToPathD, type Design, type OpParams, type Shape } from "./design.js";

export const XCS_FORMAT_NOTE =
  "Generated by xtool-mcp. .xcs is a reverse-engineered format; open in xTool Studio/XCS and verify before running. Test on scrap.";

/** MOPA pulse widths (ns) the firmware accepts; other values are rejected. */
export const LEGAL_PULSE_WIDTHS_NS = [
  2, 4, 6, 9, 13, 20, 30, 45, 60, 80, 100, 150, 200, 250, 350, 500
] as const;

export interface BuildXcsOptions {
  /** Machine object or id/name; used to fill extId/extName and light source. */
  machine?: Machine | string;
  /** Explicit xTool model code (e.g. "D1"). Overrides machine-derived value. */
  extId?: string;
  extName?: string;
  /** "blue" = diode, "red" = fiber/MOPA. Defaults from the machine category. */
  lightSource?: "blue" | "red";
  /** Material thickness in mm (used by Studio for autofocus). */
  materialThicknessMm?: number;
  /** Override the app version string written to the file. */
  version?: string;
}

type ProcessingType =
  | "VECTOR_CUTTING"
  | "VECTOR_ENGRAVING"
  | "COLOR_FILL_ENGRAVE";

function uuid(): string {
  const c = (globalThis as { crypto?: { randomUUID?: () => string } }).crypto;
  if (c?.randomUUID) return c.randomUUID();
  // Fallback (non-crypto) for older runtimes.
  return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (ch) => {
    const r = (Math.random() * 16) | 0;
    return (ch === "x" ? r : (r & 0x3) | 0x8).toString(16);
  });
}

function lightSourceFor(category: LaserCategory | undefined): "blue" | "red" {
  if (category === "fiber" || category === "infrared") return "red";
  return "blue";
}

function processingTypeFor(op: OpParams): ProcessingType {
  switch (op.type) {
    case "cut":
      return "VECTOR_CUTTING";
    case "score":
      return "VECTOR_ENGRAVING";
    case "engrave":
      return "COLOR_FILL_ENGRAVE";
  }
}

interface Bounds {
  x: number;
  y: number;
  width: number;
  height: number;
}

function shapeBounds(shape: Shape): Bounds {
  switch (shape.kind) {
    case "rect":
      return { x: shape.x, y: shape.y, width: shape.width, height: shape.height };
    case "ellipse":
      return {
        x: shape.cx - shape.rx,
        y: shape.cy - shape.ry,
        width: shape.rx * 2,
        height: shape.ry * 2
      };
    case "line":
      return {
        x: Math.min(shape.x1, shape.x2),
        y: Math.min(shape.y1, shape.y2),
        width: Math.abs(shape.x2 - shape.x1),
        height: Math.abs(shape.y2 - shape.y1)
      };
    case "polyline":
    case "polygon": {
      const xs = shape.points.map((p) => p[0]);
      const ys = shape.points.map((p) => p[1]);
      const minX = Math.min(...xs);
      const minY = Math.min(...ys);
      return { x: minX, y: minY, width: Math.max(...xs) - minX, height: Math.max(...ys) - minY };
    }
    case "text":
      return {
        x: shape.x,
        y: shape.y - shape.fontSize,
        width: Math.max(1, shape.text.length * shape.fontSize * 0.6),
        height: shape.fontSize
      };
    case "path":
      return pathBounds(shape.d);
  }
}

type Point = [number, number];
const commandSize: Record<string, number> = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, A: 7, Z: 0 };
const pathToken = /[A-Za-z]|[+-]?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?/gi;

/** Compute the physical bounds without treating relative offsets or command flags as coordinates. */
function pathBounds(d: string): Bounds {
  const tokens = d.match(pathToken) ?? [];
  const invalid = () => new Error("Invalid or unsupported SVG path data.");
  if (!/^[Mm]$/.test(tokens[0] ?? "") || d.replace(pathToken, "").replace(/[\s,]/g, "")) throw invalid();
  let x = Infinity, y = Infinity, right = -Infinity, bottom = -Infinity;
  const include = (point: Point) => {
    x = Math.min(x, point[0]);
    y = Math.min(y, point[1]);
    right = Math.max(right, point[0]);
    bottom = Math.max(bottom, point[1]);
  };
  let current: Point = [0, 0];
  let start: Point = current;
  let command = "";
  let previous = "";
  let control: Point = current;
  let drawn = false;
  for (let i = 0; i < tokens.length;) {
    const token = tokens[i]!;
    if (/^[A-Za-z]$/.test(token)) {
      command = token;
      i++;
    }
    const op = command.toUpperCase();
    const size = commandSize[op];
    if (size === undefined || i + size > tokens.length) throw invalid();
    const p = tokens.slice(i, i + size).map(Number);
    if (!p.every(Number.isFinite)) throw invalid();
    i += size;
    const relative = command !== op;
    const point = (j: number): Point => [
      p[j]! + (relative ? current[0] : 0), p[j + 1]! + (relative ? current[1] : 0)
    ];
    const reflected = (): Point => [2 * current[0] - control[0], 2 * current[1] - control[1]];
    let end = current;
    if (op === "M") {
      current = start = point(0);
      command = relative ? "l" : "L";
      previous = op;
      continue;
    }
    include(current);
    switch (op) {
      case "L": end = point(0); break;
      case "H": end = [p[0]! + (relative ? current[0] : 0), current[1]]; break;
      case "V": end = [current[0], p[0]! + (relative ? current[1] : 0)]; break;
      case "C":
      case "S": {
        const first = op === "C" ? point(0) : /[CS]/.test(previous) ? reflected() : current;
        control = point(size - 4);
        end = point(size - 2);
        includeBezier([current, first, control, end], include);
        break;
      }
      case "Q":
      case "T":
        control = op === "Q" ? point(0) : /[QT]/.test(previous) ? reflected() : current;
        end = point(size - 2);
        includeBezier([current, control, end], include);
        break;
      case "A":
        end = point(5);
        if (![p[3], p[4]].every(flag => flag === 0 || flag === 1)) throw invalid();
        includeArc(current, end, p, include);
        break;
      case "Z":
        end = start;
        command = "";
        break;
    }
    include(end);
    current = end;
    previous = op;
    drawn = true;
  }
  if (!drawn || ![x, y, right, bottom].every(Number.isFinite)) throw invalid();
  return { x, y, width: right - x, height: bottom - y };
}

function includeBezier(points: Point[], include: (point: Point) => void) {
  for (const axis of [0, 1] as const) {
    const d = points.slice(1).map((point, index) => point[axis] - points[index]![axis]);
    const a = d.length === 3 ? d[0]! - 2 * d[1]! + d[2]! : 0;
    const b = (d[1]! - d[0]!) * (d.length === 3 ? 2 : 1);
    const c = d[0]!;
    const discriminant = b * b - 4 * a * c;
    const extrema = a === 0 ? (b === 0 ? [] : [-c / b]) : (discriminant < 0 ? []
      : [(-b + Math.sqrt(discriminant)) / (2 * a), (-b - Math.sqrt(discriminant)) / (2 * a)]);
    for (const t of extrema) {
      if (!(t > 0 && t < 1)) continue;
      let remaining = points;
      while (remaining.length > 1) {
        remaining = remaining.slice(1).map((p, i): Point => [
          (1 - t) * remaining[i]![0] + t * p[0], (1 - t) * remaining[i]![1] + t * p[1]
        ]);
      }
      include(remaining[0]!);
    }
  }
}

function includeArc(start: Point, end: Point, p: number[], include: (point: Point) => void) {
  let rx = Math.abs(p[0]!), ry = Math.abs(p[1]!);
  if (!rx || !ry || (start[0] === end[0] && start[1] === end[1])) return;
  const rotation = (p[2]! % 360) * Math.PI / 180;
  const cos = Math.cos(rotation), sin = Math.sin(rotation);
  const dx = (start[0] - end[0]) / 2, dy = (start[1] - end[1]) / 2;
  const ux = cos * dx + sin * dy, uy = -sin * dx + cos * dy;
  const scale = Math.max(1, Math.hypot(ux / rx, uy / ry));
  rx *= scale;
  ry *= scale;
  const radiusCheck = (ux / rx) ** 2 + (uy / ry) ** 2;
  const coefficient = (p[3] === p[4] ? -1 : 1) * Math.sqrt(Math.max(0, 1 / radiusCheck - 1));
  const cx = coefficient * rx * uy / ry, cy = -coefficient * ry * ux / rx;
  const centerX = cos * cx - sin * cy + (start[0] + end[0]) / 2;
  const centerY = sin * cx + cos * cy + (start[1] + end[1]) / 2;
  const begin = Math.atan2((uy - cy) / ry, (ux - cx) / rx);
  const finish = Math.atan2((-uy - cy) / ry, (-ux - cx) / rx);
  const direction = p[4] === 1 ? 1 : -1;
  const period = 2 * Math.PI;
  const normalize = (angle: number) => (angle % period + period) % period;
  const sweep = normalize(direction * (finish - begin));
  const xExtreme = Math.atan2(-sin * ry, cos * rx);
  const yExtreme = Math.atan2(cos * ry, sin * rx);
  for (const angle of [xExtreme, xExtreme + Math.PI, yExtreme, yExtreme + Math.PI]) {
    if (normalize(direction * (angle - begin)) <= sweep + 1e-12) {
      include([centerX + cos * rx * Math.cos(angle) - sin * ry * Math.sin(angle),
        centerY + sin * rx * Math.cos(angle) + cos * ry * Math.sin(angle)]);
    }
  }
}

function buildDisplay(shape: Shape): Record<string, unknown> {
  const b = shapeBounds(shape);
  const isFill = shape.op.type === "engrave";
  const common: Record<string, unknown> = {
    id: shape.id,
    name: null,
    x: round(b.x),
    y: round(b.y),
    angle: 0,
    scale: { x: 1, y: 1 },
    skew: { x: 0, y: 0 },
    pivot: { x: 0, y: 0 },
    localSkew: { x: 0, y: 0 },
    offsetX: round(b.x),
    offsetY: round(b.y),
    lockRatio: false,
    zOrder: 0,
    groupTags: [],
    width: round(b.width),
    height: round(b.height),
    isFill,
    lineColor: 0,
    fillColor: "#000000"
  };

  switch (shape.kind) {
    case "rect":
      return { ...common, type: "RECT", isClosePath: true };
    case "ellipse": {
      if (Math.abs(shape.rx - shape.ry) < 1e-6) {
        const diameter = shape.rx * 2;
        // CRITICAL: CIRCLE requires scale = width / 5900 or it renders invisible.
        return {
          ...common,
          type: "CIRCLE",
          isClosePath: true,
          lockRatio: true,
          scale: { x: diameter / 5900, y: diameter / 5900 }
        };
      }
      return { ...common, type: "PATH", isClosePath: true, points: [], dPath: shapeToPathD(shape) };
    }
    case "line":
      return {
        ...common,
        type: "PATH",
        isClosePath: false,
        points: [],
        dPath: shapeToPathD(shape)
      };
    case "polyline":
    case "polygon":
      return {
        ...common,
        type: "PATH",
        isClosePath: shape.kind === "polygon",
        points: [],
        dPath: shapeToPathD(shape)
      };
    case "path": {
      const subpaths = shape.d.trim().split(/(?=[Mm])/);
      return {
        ...common, type: "PATH", isClosePath: subpaths.every(subpath => /[Zz]\s*$/.test(subpath)),
        points: [], dPath: shape.d
      };
    }
    case "text":
      return {
        ...common,
        type: "TEXT",
        text: shape.text,
        style: {
          fontFamily: "Arial",
          fontSubfamily: "Regular",
          fontSource: "build-in",
          fontSize: shape.fontSize,
          letterSpacing: 0,
          leading: shape.fontSize * 1.2,
          align: "left"
        }
      };
  }
}

function clampNum(v: number, min: number, max: number): number {
  if (!Number.isFinite(v)) return min;
  return Math.min(max, Math.max(min, v));
}

function buildProcessingEntry(shape: Shape, lightSource: "blue" | "red"): Record<string, unknown> {
  const pt = processingTypeFor(shape.op);
  const isFill = shape.op.type === "engrave";
  // Clamp to physically valid ranges so a stray parameter can't emit an unsafe/invalid job.
  const customize: Record<string, unknown> = {
    power: clampNum(shape.op.power_pct, 0, 100),
    speed: Math.max(0.1, Number.isFinite(shape.op.speed_mm_s) ? shape.op.speed_mm_s : 100),
    repeat: clampNum(Math.round(shape.op.passes), 1, 50),
    processingLightSource: lightSource,
    pulseWidth: 200,
    mopaFrequency: 65
  };
  if (pt === "COLOR_FILL_ENGRAVE") {
    customize.density = 100;
    customize.dpi = clampNum(Math.round(shape.op.dpi ?? 300), 10, 4000);
    customize.dotDuration = 100;
    customize.bitmapEngraveMode = "normal";
    customize.bitmapScanMode = "zMode";
    customize.scanAngle = 90;
    customize.angleType = 1;
    customize.crossAngle = false;
  } else {
    customize.enableKerf = false;
    customize.kerfDistance = 0;
  }

  return {
    type: displayType(shape),
    isFill,
    processingType: pt,
    processIgnore: false,
    data: {
      [pt]: {
        materialType: "customize",
        parameter: { customize }
      }
    }
  };
}

function displayType(shape: Shape): string {
  if (shape.kind === "rect") return "RECT";
  if (shape.kind === "text") return "TEXT";
  if (shape.kind === "ellipse" && Math.abs(shape.rx - shape.ry) < 1e-6) return "CIRCLE";
  return "PATH";
}

function round(v: number): number {
  return Math.round(v * 1000) / 1000;
}

export interface BuiltXcs {
  /** The `.xcs` document as a JS object. */
  doc: Record<string, unknown>;
  /** Pretty-printed JSON string ready to write to a `.xcs` file. */
  json: string;
  extId: string;
  extName: string;
  warnings: string[];
}

export function buildXcs(design: Design, options: BuildXcsOptions = {}): BuiltXcs {
  const warnings: string[] = [];
  const machine =
    typeof options.machine === "string" ? getMachine(options.machine) : options.machine;

  const curatedExtId = machine?.xcs_ext_id;
  const extId = options.extId ?? curatedExtId ?? deriveExtId(machine);
  const extName =
    options.extName ?? machine?.xcs_ext_name ?? machine?.name?.replace(/^xTool\s+/i, "") ?? extId;
  const lightSource = options.lightSource ?? lightSourceFor(machine?.category);

  if (!options.extId && !curatedExtId) {
    warnings.push(
      machine
        ? `extId was derived as "${extId}" and is NOT a verified xTool model code — confirm it in Studio, or pass extId explicitly.`
        : "No machine specified; extId defaulted. Set the correct machine so Studio targets the right device."
    );
  }

  const canvasId = uuid();
  const now = Date.now();

  const displays = design.shapes.map(buildDisplay);
  const processingPairs = design.shapes.map((shape) => [
    shape.id,
    buildProcessingEntry(shape, lightSource)
  ]);

  const doc: Record<string, unknown> = {
    canvasId,
    version: options.version ?? "1.7.24",
    extId,
    extName,
    created: now,
    modify: now,
    ua: "xtool-mcp",
    meta: [],
    projectTraceID: uuid(),
    canvas: [
      {
        id: canvasId,
        title: design.meta?.title ? design.meta.title.slice(0, 40) : "{panel}1",
        displays
      }
    ],
    device: {
      id: extId,
      extId,
      extName,
      power: machine?.default_laser_power_w ?? machine?.laser_power_w.at(-1) ?? 0,
      materialList: [],
      data: {
        dataType: "Map",
        value: [
          [
            canvasId,
            {
              mode: "LASER_PLANE",
              data: {
                LASER_PLANE: {
                  material: 0,
                  thickness: options.materialThicknessMm ?? null,
                  lightSourceMode: lightSource
                }
              },
              displays: {
                dataType: "Map",
                value: processingPairs
              }
            }
          ]
        ]
      }
    }
  };

  return { doc, json: JSON.stringify(doc, null, 2), extId, extName, warnings };
}

function deriveExtId(machine: Machine | undefined): string {
  if (!machine) return "D1";
  // Best-effort: strip "xTool " and spaces. Known codes should be curated in data.
  return machine.name.replace(/^xTool\s+/i, "").replace(/\s+/g, "").toUpperCase();
}
